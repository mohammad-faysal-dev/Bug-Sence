import { BugAnalysis, AnalysisRequest } from "@/lib/types";
import { LANGUAGE_LABELS, formatDate, SEVERITY_CONFIG } from "@/lib/utils";

export function generateMarkdownReport(
  result: BugAnalysis,
  request: AnalysisRequest,
  createdAt: string
): string {
  const sevConfig = SEVERITY_CONFIG[result.severity] || SEVERITY_CONFIG.medium;
  const langLabel = LANGUAGE_LABELS[request.language] || request.language;

  return `# ⚡ BugSense AI — Diagnostic & Patch Report

**Generated:** ${formatDate(createdAt)}  
**Language:** ${langLabel}  
**Severity:** ${sevConfig.label.toUpperCase()}  

---

## 🛑 1. Error Summary
> ${result.errorSummary}

### Raw Error / Stack Trace
\`\`\`${request.language}
${request.errorMessage}
\`\`\`

${
  request.codeSnippet
    ? `### Original Code Context
\`\`\`${request.language}
${request.codeSnippet}
\`\`\`
`
    : ""
}

---

## 🔍 2. Root Cause Analysis
${result.possibleCause}

### Technical Breakdown
${result.explanation}

---

## 🛠️ 3. Step-by-Step Resolution Plan
${result.suggestedSolution}

${
  result.codeExample
    ? `---

## 💻 4. Repaired Code Patch
\`\`\`${request.language}
${result.codeExample}
\`\`\`
`
    : ""
}

---
*Generated by [BugSense AI](https://bugsence.vercel.app) — Automated Code Diagnostics Suite*
`;
}

export function downloadMarkdownFile(
  result: BugAnalysis,
  request: AnalysisRequest,
  createdAt: string
) {
  const content = generateMarkdownReport(result, request, createdAt);
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  const timestamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
  link.href = url;
  link.download = `bugsense-report-${request.language}-${timestamp}.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

